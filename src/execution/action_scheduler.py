"""
ActionSequenceScheduler — unified timeline scheduler for multi-channel execution.
v4.5.0 §7.2

Orchestrates ActionSequence scripts distributed across avatar_channel,
mouse_channel, voice_channel (and bubble for text bubbles). Execution is
driven by TTS streaming progress (elapsed_ms) as the single clock source.

Key behaviours:
  - TTS-progress-driven dispatch (start_ms <= elapsed_ms + 50ms tolerance)
  - skip_decision=True actions have lower priority than user-triggered actions
  - Mouse deadline enforcement (force-jump if near deadline)
  - User mid-speech interrupt stops all channels immediately
  - CharDurationPredictor fallback when CosyVoice word-alignment unavailable
"""
