logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Channel name constants — 项目宪法 §2.3
# ---------------------------------------------------------------------------

CHANNEL_AVATAR = "avatar"
CHANNEL_MOUSE = "mouse"
CHANNEL_VOICE = "voice"
CHANNEL_BUBBLE = "bubble"

VALID_CHANNELS: frozenset[str] = frozenset(
    {CHANNEL_AVATAR, CHANNEL_MOUSE, CHANNEL_VOICE, CHANNEL_BUBBLE}
)

# Default dispatch tolerance in ms — v4.5.0 §7.2.2
DEFAULT_DISPATCH_TOLERANCE_MS = 50

# Default mouse deadline threshold — if remaining time < this, force-jump
DEFAULT_MOUSE_DEADLINE_THRESHOLD_MS = 100


# ---------------------------------------------------------------------------
# Data structures — v4.5.0 §7.2.1
# ---------------------------------------------------------------------------

@dataclass
class Action:
    """A single action in an ActionSequence.

    v4.5.0 §7.2.1: Each action targets one channel and carries timing info.
    """

    channel: str
    """Target channel: avatar, mouse, voice, or bubble."""

    type: str
    """Action type: expression, motion, move_to, click, text, etc."""

    start_ms: int
    """Start time relative to sequence start in milliseconds."""

    value: str | None = None
    """Action value (e.g., expression name, text content)."""

    target: dict[str, Any] | None = None  # pyright: ignore[reportExplicitAny]
    """Target coordinates for mouse actions: {"x": int, "y": int}."""

    duration_ms: int | None = None
    """Duration in milliseconds (for expressions, motions)."""

    deadline_ms: int | None = None
    """Deadline by which the action must complete (for mouse actions)."""

    def __post_init__(self) -> None:
        """Validate channel name — 项目宪法 §2.1 zero-tolerance naming."""
        if self.channel not in VALID_CHANNELS:
            logger.warning(
                "Unknown channel %r in action — valid channels: %s. trace_id=TBD",
                self.channel,
                sorted(VALID_CHANNELS),
            )


@dataclass
class ActionSequence:
    """A timeline of multi-channel actions to execute.

    v4.5.0 §7.2.1: Generated by the scheduler, distributed to channels.
    """

    sequence_id: str = field(default_factory=lambda: uuid.uuid4().hex)
    """Unique identifier for this sequence."""

    actions: list[Action] = field(default_factory=list)
    """Ordered list of actions in this sequence."""

    skip_decision: bool = False
    """True when submitted by external modules (prediction layer etc.).
    These actions have lower priority than user-triggered decision actions.
    v4.5.0 §7.2.1 ¶4"""

    source: str = "decision"
    """Origin of this sequence: 'decision', 'prediction', 'reflex', etc."""

    def get_ready_actions(
        self, elapsed_ms: int, tolerance_ms: int = DEFAULT_DISPATCH_TOLERANCE_MS
    ) -> list[Action]:
        """Return actions whose start_ms <= elapsed_ms + tolerance_ms.

        v4.5.0 §7.2.2: On each audio chunk with elapsed_ms, pull all actions
        where start_ms <= elapsed_ms + 50ms and execute them.
        """
        threshold = elapsed_ms + tolerance_ms
        return [a for a in self.actions if a.start_ms <= threshold]

    def get_channel_actions(self, channel: str) -> list[Action]:
        """Filter actions by target channel."""
        return [a for a in self.actions if a.channel == channel]

    def to_dict(self) -> dict[str, Any]:
        """Serialize to dict matching the spec JSON format."""
        return {
            "sequence_id": self.sequence_id,
            "actions": [
                {
                    "channel": a.channel,
                    "type": a.type,
                    **({"value": a.value} if a.value is not None else {}),
                    **({"target": a.target} if a.target is not None else {}),
                    "start_ms": a.start_ms,
                    **(
                        {"duration_ms": a.duration_ms}
                        if a.duration_ms is not None
                        else {}
                    ),
                    **(
                        {"deadline_ms": a.deadline_ms}
                        if a.deadline_ms is not None
                        else {}
                    ),
                }
                for a in self.actions
            ],
        }

    def __bool__(self) -> bool:
        """An empty sequence is falsy."""
        return bool(self.actions)


